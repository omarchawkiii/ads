<?php

namespace App\Console\Commands;

use App\Models\Invoice;
use Illuminate\Console\Command;

class PurgeLegacyInvoices extends Command
{
    protected $signature = 'invoices:purge-legacy {--force : Supprime réellement (sinon simple aperçu)}';

    protected $description = 'Supprime les anciennes factures au budget fixe (sans lignes de facturation ni paiement) pour que invoices:generate les recrée';

    public function handle(): int
    {
        $invoices = Invoice::doesntHave('lines')->doesntHave('payments')->get();

        if ($invoices->isEmpty()) {
            $this->info('No legacy invoice to purge.');
            return self::SUCCESS;
        }

        $this->table(
            ['id', 'number', 'campaign', 'total_ttc'],
            $invoices->map(fn ($i) => [$i->id, $i->number, $i->compaign_id, $i->total_ttc])->all()
        );

        if (!$this->option('force')) {
            $this->warn('Preview only. Re-run with --force to delete these invoices.');
            return self::SUCCESS;
        }

        $invoices->each->delete();
        $this->info($invoices->count() . ' invoice(s) deleted. They will be regenerated by invoices:generate once their campaign has ended.');

        return self::SUCCESS;
    }
}
